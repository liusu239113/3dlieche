-- Isolated real UI tree/input/render validation. No main, SaveStore, cloud or player files.
-- Run at 640x360,800x450,1280x720,1568x994 using the existing runtime CLI dimensions.
local Hud=require "ui.Hud"
local UI=require "urhox-libs/UI"
local Timetable=require "game.Timetable"
local checks_,frames_=0,0
local failed_,done_=false,false
local captureName_,captureTries_,captureWarm_,captures_= "",0,false,0
local stage_,savedFrame_="map",0
local function requestCapture(name)
    captureName_,captureTries_,captureWarm_=name,0,false
end
local function check(value,message) checks_=checks_+1;assert(value,"[TimetableLayout] "..message) end
local function root() return assert(Hud.GetRoot()) end
local function tap(id,scrollId)
    UI.Layout()
    local widget=assert(root():FindById(id),"missing "..id)
    if scrollId then
        local scroll=assert(root():FindById(scrollId)) --[[@as ScrollView]]
        scroll:UpdateContentSize()
        local r,b=widget:GetAbsoluteLayoutForHitTest(),scroll:GetAbsoluteLayoutForHitTest()
        scroll:ScrollBy(0,r.y+r.h*.5-b.y-b.h*.5)
        UI.Layout()
    end
    local r=widget:GetAbsoluteLayoutForHitTest()
    check(r.w>=43.5 and r.h>=43.5,"touch target <44 (pixel snapping tolerance): "..id)
    local x,y=r.x+r.w*.5,r.y+r.h*.5
    check(UI.FindWidgetAt(x,y)==widget,"real hit target obscured: "..id)
    UI.InputAdapter.HandleTouchBegin(779,x*UI.GetScale(),y*UI.GetScale(),.5)
    UI.InputAdapter.HandleTouchEnd(779,x*UI.GetScale(),y*UI.GetScale())
end
local function noOverlap(a,b)
    return a.x+a.w<=b.x+.1 or b.x+b.w<=a.x+.1 or a.y+a.h<=b.y+.1 or b.y+b.h<=a.y+.1
end
local function mockSnapshot()
    -- UI fixture generated by the production pure model, explicitly NOT a gameplay screenshot.
    local clock={minutes=725,rate=.4,revision=0,running=true,paused=false}
    local stations={}
    local names={"星汐总站","岚港站","榆岑站","镜澜站","云湾总站"}
    for i=1,5 do stations[i]={index=i,name=names[i],s=1000+(i-1)*7000} end
    local options={s=1001,reversing=false,service="local",journeyId=1,originIndex=1,
        operatingKmh=160,lineKmh=350,stationKmh=60,deceleration=.7,segments={}}
    local model=Timetable.new(clock,stations,options)
    return model:GetStatus({s=1001,speedMs=0,operatingKmh=160,deceleration=.7,dwelling=true,
        terminal=false,minimumDwellSeconds=12,passengerReady=false,departureBlocked=true,departureReason="passengers"})
end
function Start()
    local ok,message=xpcall(function()
        Hud.Init({onThrottleUp=function() end,onThrottleDown=function() end,onBrake=function() end,
            onReleaseBrake=function() end,onSelectCamera=function() return true end,onCamera=function() end,
            onSoundToggle=function(enabled) Hud.SetSoundEnabled(enabled) end,
            onSettings=function() end,onService=function() end,onDrivingMode=function() end})
        Hud.SetEnvironment({clockText="12:05",weatherLabel="晴",running=true,paused=false})
        Hud.SetPassengerStatus({phase="boarding",waiting=200,onboard=194,capacity=560,ready=false,doorsOpen=true,
            boarded=194,totalBoarding=394,totalAlighting=0,alighted=0,message="候车队列逐人走向车门"})
        Hud.SetTimetable(mockSnapshot())
        local points={}
        for i=1,20 do points[i]={pos=Vector3(i*10,0,i*60)} end
        Hud.BuildMinimap(points,{{x=10,z=60},{x=100,z=600},{x=200,z=1200}})
        SubscribeToEvent("Update","HandleUpdate")
        SubscribeToEvent("EndRendering","TimetableLayoutCapture")
    end,debug.traceback)
    if not ok then failed_=true;print("TIMETABLE_LAYOUT_FAIL "..tostring(message));engine:Exit() end
end
function HandleUpdate(eventType,eventData)
    if failed_ then return end
    local ok,message=xpcall(function()
        frames_=frames_+1
        if frames_==5 then
            tap("toggleMinimap")
            UI.Layout()
            check(Hud.GetReadings().mapVisible,"map did not open")
            local l=Hud.GetLayout()
            check(math.abs(l.routeDropdown.x-l.mapButton.x)<1,"dropdown not anchored to 线路 button")
            check(l.routeDropdown.y>=l.mapButton.y+l.mapButton.h+5,"dropdown not directly below action")
            check(noOverlap(l.routeDropdown,l.controls),"dropdown covers driving desk")
            check(noOverlap(l.routeDropdown,l.speedometer),"dropdown covers speedometer")
            local vw,vh=UI.GetViewportSize()
            check(l.routeDropdown.x>=0 and l.routeDropdown.y+l.routeDropdown.h<=vh
                and l.routeDropdown.x+l.routeDropdown.w<=vw,"dropdown outside viewport")
            print(string.format("[TimetableLayout] viewport %.1fx%.1f action %.1f,%.1f dropdown %.1f,%.1f %.1fx%.1f deskTop %.1f",
                vw,vh,l.mapButton.x,l.mapButton.y,l.routeDropdown.x,l.routeDropdown.y,l.routeDropdown.w,l.routeDropdown.h,l.controls.y))
            requestCapture("map")
        elseif stage_=="map" and captures_==1 and frames_>savedFrame_+2 then
            tap("routeTimetableTab")
            check(assert(root():FindById("timetableScroll")):IsVisible(),"timetable tab did not switch")
            local scroll=assert(root():FindById("timetableScroll")) --[[@as ScrollView]]
            scroll:UpdateContentSize();scroll:ScrollToBottom();UI.Layout()
            check(select(2,scroll:GetScroll())>0,"small timetable not scrollable")
            scroll:ScrollToTop()
            stage_="timetable";requestCapture("timetable")
        elseif stage_=="timetable" and captures_==2 and frames_>savedFrame_+2 then
            tap("closeRouteDropdown");check(not Hud.GetReadings().mapVisible,"close action failed")
            tap("toggleOperations")
            tap("openSettings","operationsDetails")
            tap("toggleMinimap");tap("routeMapTab")
            tap("closeRouteDropdown");tap("toggleMinimap");tap("routeTimetableTab")
            stage_="reopen";requestCapture("timetable-reopen")
        elseif stage_=="reopen" and captures_==3 and frames_>savedFrame_+2 then
            done_=true
            print("ALL_TIMETABLE_LAYOUT_PASS checks="..checks_.." captures="..captures_.." physical="..graphics:GetWidth().."x"..graphics:GetHeight())
            engine:Exit()
        end
        check(frames_<500,"bounded frame budget exceeded")
    end,debug.traceback)
    if not ok then failed_=true;print("TIMETABLE_LAYOUT_FAIL "..tostring(message));log:Write(LOG_ERROR,tostring(message));engine:Exit() end
end
function TimetableLayoutCapture()
    if failed_ or captureName_=="" or frames_<125 or frames_%3~=0 then return end
    local ok,message=xpcall(function()
        captureTries_=captureTries_+1
        local image=Image()
        local read=graphics:TakeScreenShot(image)
        if read and captureWarm_ then
            assert(image:SavePNG("/workspace/screenshots/timetable-ui-"..graphics:GetWidth().."x"..graphics:GetHeight().."-"..captureName_..".png"))
            captures_,savedFrame_,captureName_=captures_+1,frames_,""
        elseif read then captureWarm_=true end
        image:Dispose()
        check(captureName_=="" or captureTries_<6,"readback failed after six bounded attempts")
    end,debug.traceback)
    if not ok then failed_=true;print("TIMETABLE_LAYOUT_FAIL "..tostring(message));log:Write(LOG_ERROR,tostring(message));engine:Exit() end
end
function Stop() Hud.Shutdown() end
